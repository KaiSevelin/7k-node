/**
 * A TypeScript provider for 7K.
 *
 * Its own repository, because D48 puts implementations outside the language: 7K states what the data
 * is and this says whether TypeScript can hold it.
 *
 * **It generates a decoder where the C# provider generates a validator, and the difference is not
 * stylistic.** A C# message is checked by the compiler and arrives as the type it claims; a TypeScript
 * one arrives as `unknown`, and `JSON.parse(body) as PlaceOrder` compiles. So every type here has
 * exactly one way in — a function from `unknown` to either the value or the reasons it is not one — and
 * that function is the only thing between the wire and the code that knows what the model said.
 *
 * **The branded kernel types are what make the encoding free.** A `Uuid` is the string the wire carried
 * and a distinct type at compile time, so a decoded message is canonical JSON under `JSON.stringify`
 * with no serializer, and a `decimal(18,2)` stays the string the contract says it is rather than
 * becoming the double that would round it.
 *
 * It covers the Data layer. Handler interfaces and the saga machine are the next increment, and
 * deliberately not half-done here.
 */

